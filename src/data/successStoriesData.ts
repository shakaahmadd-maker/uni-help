export function maskStudentName(name: string): string {
  const parts = name.trim().split(/\s+/);
  if (parts.length > 1) {
    return parts.map((part) => {
      if (part.length <= 2) return `${part.charAt(0)}*`;
      return `${part.charAt(0)}***${part.charAt(part.length - 1)}`.toUpperCase();
    }).join(" ");
  }
  if (name.length <= 2) return `${name.charAt(0)}*`.toUpperCase();
  return `${name.charAt(0)}***${name.charAt(name.length - 1)}`.toUpperCase();
}

